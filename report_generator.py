def generate_master_report(
    patient_name,
    patient_age,
    patient_gender,
    bone_data=None,
    mri_ct_data=None,
    report_analysis_data=None,
    symptom_advisor_data=None,
    output_path=None
):
    """
    Generate a comprehensive master report combining all sections.
    
    Args:
        bone_data: dict with keys: fracture_type, confidence, severity, description, treatment,
                   original_image_path, highlighted_image_path, thermal_image_path
        mri_ct_data: dict with keys: scan_type, anomaly_type, confidence, severity, description, treatment,
                     original_image_path, highlighted_image_path, thermal_image_path
        report_analysis_data: dict with key: summary_text
        symptom_advisor_data: dict with keys: symptoms, advice_text
    """
    pdf = MedicalReportPDF('MediVision AI - Comprehensive Multi-Modality Diagnostic Report')
    pdf.alias_nb_pages()
    pdf.add_page()

    # Patient Information
    pdf.add_section_title('PATIENT INFORMATION')
    pdf.add_field('Patient Name:', patient_name)
    pdf.add_field('Age:', f'{patient_age} years')
    pdf.add_field('Gender:', patient_gender)
    pdf.add_field('Report Date:', datetime.now().strftime('%B %d, %Y'))
    pdf.add_field('Report Time:', datetime.now().strftime('%I:%M %p'))
    pdf.ln(4)

    # Table of Contents
    pdf.add_section_title('TABLE OF CONTENTS')
    toc_items = []
    if bone_data:
        toc_items.append('1. Bone Fracture Detection (X-Ray Analysis)')
    if mri_ct_data:
        toc_items.append(f"2. {mri_ct_data.get('scan_type', 'MRI/CT')} Scan Anomaly Analysis")
    if report_analysis_data:
        toc_items.append('3. Medical Report AI Analysis Summary')
    if symptom_advisor_data:
        toc_items.append('4. Symptom & Medicine Advisory')
    
    for item in toc_items:
        pdf.set_font('Helvetica', '', 10)
        pdf.set_text_color(30, 41, 59)
        pdf.cell(0, 7, item, 0, 1)
    pdf.ln(4)

    # Section 1: Bone Detection
    if bone_data:
        pdf.add_section_title('1. BONE FRACTURE DETECTION - X-RAY ANALYSIS')
        pdf.add_field('Fracture Type:', bone_data.get('fracture_type', 'N/A').capitalize())
        pdf.add_field('Confidence Level:', f"{bone_data.get('confidence', 0):.2f}%")
        pdf.add_field('Severity:', bone_data.get('severity', 'N/A'))
        pdf.ln(2)
        
        pdf.add_section_title('CLINICAL DESCRIPTION')
        pdf.add_multiline_text(bone_data.get('description', 'N/A'))
        
        pdf.add_section_title('RECOMMENDED TREATMENT PLAN')
        pdf.add_multiline_text(bone_data.get('treatment', 'N/A'))
        pdf.ln(4)

        pdf.add_section_title('MEDICAL IMAGING - X-RAY')
        pdf.set_font('Helvetica', 'B', 10)
        pdf.set_text_color(30, 41, 59)
        pdf.cell(0, 7, '1.1 Original X-Ray Image', 0, 1)
        pdf.add_image_with_caption(bone_data.get('original_image_path'), 'Original X-Ray Image', max_width=160, max_height=100)
        
        pdf.ln(2)
        pdf.cell(0, 7, '1.2 Fracture Highlighted Detection View', 0, 1)
        pdf.add_image_with_caption(bone_data.get('highlighted_image_path'), 'AI-Detected Fracture Region (Red Boundary & Crosshairs)', max_width=160, max_height=100)
        
        pdf.ln(2)
        pdf.cell(0, 7, '1.3 Thermal Intensity Heatmap View', 0, 1)
        pdf.add_image_with_caption(bone_data.get('thermal_image_path'), 'Thermal Gradient Heatmap (JET Colormap)', max_width=160, max_height=100)
        pdf.ln(6)

    # Section 2: MRI/CT
    if mri_ct_data:
        pdf.add_section_title(f"2. {mri_ct_data.get('scan_type', 'MRI/CT').upper()} SCAN ANOMALY ANALYSIS")
        pdf.add_field('Anomaly Classification:', mri_ct_data.get('anomaly_type', 'N/A').replace('_', ' ').title())
        pdf.add_field('Confidence Level:', f"{mri_ct_data.get('confidence', 0):.2f}%")
        pdf.add_field('Severity:', mri_ct_data.get('severity', 'N/A'))
        pdf.ln(2)
        
        pdf.add_section_title('CLINICAL DESCRIPTION')
        pdf.add_multiline_text(mri_ct_data.get('description', 'N/A'))
        
        pdf.add_section_title('RECOMMENDED TREATMENT PLAN')
        pdf.add_multiline_text(mri_ct_data.get('treatment', 'N/A'))
        pdf.ln(4)

        pdf.add_section_title(f'MEDICAL IMAGING - {mri_ct_data.get("scan_type", "MRI/CT").upper()}')
        pdf.set_font('Helvetica', 'B', 10)
        pdf.set_text_color(30, 41, 59)
        pdf.cell(0, 7, f'2.1 Original {mri_ct_data.get("scan_type", "MRI/CT")} Scan Image', 0, 1)
        pdf.add_image_with_caption(mri_ct_data.get('original_image_path'), f'Original {mri_ct_data.get("scan_type", "MRI/CT")} Scan', max_width=160, max_height=100)
        
        pdf.ln(2)
        pdf.cell(0, 7, f'2.2 Anomaly Highlighted View', 0, 1)
        pdf.add_image_with_caption(mri_ct_data.get('highlighted_image_path'), f'AI-Detected Anomaly Region', max_width=160, max_height=100)
        
        pdf.ln(2)
        pdf.cell(0, 7, f'2.3 Thermal Intensity Heatmap View', 0, 1)
        pdf.add_image_with_caption(mri_ct_data.get('thermal_image_path'), f'Thermal Gradient Heatmap (JET Colormap)', max_width=160, max_height=100)
        pdf.ln(6)

    # Section 3: Report Analysis
    if report_analysis_data:
        pdf.add_section_title('3. MEDICAL REPORT AI ANALYSIS SUMMARY')
        pdf.add_multiline_text(report_analysis_data.get('summary_text', 'N/A'))
        pdf.ln(6)

    # Section 4: Symptom Advisor
    if symptom_advisor_data:
        pdf.add_section_title('4. SYMPTOM & MEDICINE ADVISORY')
        pdf.add_section_title('REPORTED SYMPTOMS')
        pdf.add_multiline_text(symptom_advisor_data.get('symptoms', 'N/A'))
        pdf.ln(2)
        
        pdf.add_section_title('MEDICINE SUGGESTIONS & CLINICAL ADVISORY')
        pdf.add_multiline_text(symptom_advisor_data.get('advice_text', 'N/A'))
        pdf.ln(6)

    pdf.add_disclaimer()
    pdf.output(output_path)
    return output_path


